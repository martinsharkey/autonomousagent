def is_within_contact_window() -> bool:
    """Check if current time is within the allowed contact window (18:00-21:00 GMT)."""
    now_utc = datetime.now(timezone.utc)
    # GMT = UTC (no daylight saving adjustment for GMT itself)
    hour = now_utc.hour
    return 18 <= hour < 21


