# ─── Challenge State Management ──────────────────────────────────────────────

class ChallengeManager:
    """Manages autonomous challenge state and progress."""

    def __init__(self):
        self.challenges = {c["id"]: dict(c) for c in CHALLENGES}
        self.attempts: List[Dict[str, Any]] = []
        self._load_state()

    def _load_state(self):
        """Load challenge state from disk."""
        try:
            if CHALLENGES_FILE.exists():
                with open(CHALLENGES_FILE) as f:
                    data = json.load(f)
                for cid, state in data.get("challenges", {}).items():
                    if cid in self.challenges:
                        self.challenges[cid].update(state)
            if CHALLENGE_LOG_FILE.exists():
                with open(CHALLENGE_LOG_FILE) as f:
                    self.attempts = json.load(f)
        except Exception:
            pass

    def _save_state(self):
        """Persist challenge state."""
        try:
            CHALLENGES_FILE.parent.mkdir(parents=True, exist_ok=True)
            with open(CHALLENGES_FILE, "w") as f:
                json.dump({
                    "challenges": self.challenges,
                    "last_updated": datetime.now(timezone.utc).isoformat(),
                }, f, indent=2)
        except Exception:
            pass

    def _save_attempts(self):
        """Persist attempt log."""
        try:
            CHALLENGE_LOG_FILE.parent.mkdir(parents=True, exist_ok=True)
            with open(CHALLENGE_LOG_FILE, "w") as f:
                json.dump(self.attempts[-200:], f, indent=2)
        except Exception:
            pass

    def get_active_challenges(self) -> List[Dict[str, Any]]:
        """Get challenges the council should be working on."""
        active = []
        for challenge in self.challenges.values():
            if challenge["status"] == "active":
                active.append(challenge)
            elif challenge["status"] == "pending":
                # Check if prerequisites are met
                requires = challenge.get("requires", [])
                all_met = all(
                    self.challenges.get(req, {}).get("status") == "completed"
                    for req in requires
                )
                if all_met:
                    challenge["status"] = "active"
                    self._save_state()
                    active.append(challenge)
        return active

    def get_challenge_prompt(self) -> str:
        """Generate prompt text for agent context injection."""
        active = self.get_active_challenges()
        if not active:
            return ""

        lines = [
            "\n═══ AUTONOMY CHALLENGES ═══",
            "The following challenges test your ability to act independently.",
            "You must solve these WITHOUT human assistance.",
            f"Contact window: 18:00-21:00 GMT only. Currently {'OPEN' if is_within_contact_window() else 'CLOSED'}.",
            "",
        ]

        for i, challenge in enumerate(active, 1):
            attempts = self._count_attempts(challenge["id"])
            max_att = challenge.get("max_attempts", 10)
            lines.append(f"{'─' * 40}")
            lines.append(f"CHALLENGE {i}: {challenge['title']}")
            lines.append(f"Attempts: {attempts}/{max_att}")
            lines.append(f"\n{challenge['description']}")
            lines.append("")

        lines.append("═══ END CHALLENGES ═══\n")
        return "\n".join(lines)

    def _count_attempts(self, challenge_id: str) -> int:
        """Count attempts for a specific challenge."""
        return sum(1 for a in self.attempts if a.get("challenge_id") == challenge_id)

    def log_attempt(
        self,
        challenge_id: str,
        agent_name: str,
        method: str,
        success: bool,
        details: Optional[Dict[str, Any]] = None,
    ):
        """Log a challenge attempt."""
        attempt = {
            "challenge_id": challenge_id,
            "agent_name": agent_name,
            "method": method,
            "success": success,
            "details": details or {},
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "within_window": is_within_contact_window(),
        }
        self.attempts.append(attempt)
        self._save_attempts()

        if success:
            self.mark_completed(challenge_id)

    def mark_completed(self, challenge_id: str):
        """Mark a challenge as completed."""
        if challenge_id in self.challenges:
            self.challenges[challenge_id]["status"] = "completed"
            self.challenges[challenge_id]["completed_at"] = datetime.now(timezone.utc).isoformat()
            self._save_state()
            # Check if this unlocks new challenges
            self.get_active_challenges()

    def get_progress_summary(self) -> Dict[str, Any]:
        """Get overall challenge progress."""
        total = len(self.challenges)
        completed = sum(1 for c in self.challenges.values() if c["status"] == "completed")
        active = sum(1 for c in self.challenges.values() if c["status"] == "active")
        pending = sum(1 for c in self.challenges.values() if c["status"] == "pending")

        return {
            "total_challenges": total,
            "completed": completed,
            "active": active,
            "pending": pending,
            "completion_percentage": round(completed / total * 100, 1) if total else 0,
            "total_attempts": len(self.attempts),
            "challenges": {
                cid: {
                    "title": c["title"],
                    "status": c["status"],
                    "attempts": self._count_attempts(cid),
                }
                for cid, c in self.challenges.items()
            },
        }


